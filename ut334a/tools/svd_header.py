"""Cross-check the FM33 DFP header against the SVD and emit register bit definitions.

Usage: svd_header.py fm33lc0xx.h FM33LC0XX.SVD out.h

- For every peripheral instance in the header (`#define X ((T_Type *) X_BASE)`), each struct member's absolute
  address is compared with the SVD register of the same name (SVD peripheral matched by name, else by base).
  Disagreements are printed and written into out.h as comments; settle them with the datasheet.
- out.h gets `<T>_<REG>_<FIELD>_Pos/_Msk` for every register of every header type (T = struct name without
  `_Type`), taken from the SVD peripheral of the type's first instance. Registers whose address disagrees still
  get their fields (bit layouts are per register, not per address) but are marked.
"""
import re
import sys
import os

sys.path.insert(0, os.path.dirname(__file__))
import xml.etree.ElementTree as ET


def parse_header(path):
    text = open(path, encoding='utf-8', errors='replace').read()
    bases = {'PERIPH_BASE': 0x40000000}
    for name, expr in re.findall(r'#define\s+(\w+_BASE)\s+(\(.*?\)|0x[0-9A-Fa-f]+UL)', text):
        m = re.match(r'\(\s*(\w+)\s*\+\s*(0x[0-9A-Fa-f]+)UL\s*\)', expr)
        if m:
            bases[name] = bases[m.group(1)] + int(m.group(2), 16)
        else:
            bases[name] = int(expr.rstrip('UL'), 16)
    types = {}
    for body, tname in re.findall(r'typedef struct\s*\{(.*?)\}\s*(\w+_Type)\s*;', text, re.S):
        off, members = 0, []
        for line in body.splitlines():
            m = re.match(r'\s*__(?:IO|IM|OM|I|O)\s+uint32_t\s+(\w+)(?:\[(\d+)\])?\s*;', line)
            if not m:
                continue
            n = int(m.group(2) or 1)
            if not m.group(1).startswith('RSV'):
                members.append((m.group(1), off))
            off += 4 * n
        types[tname] = members
    instances = []
    for inst, tname, base in re.findall(r'#define\s+(\w+)\s+\(\(\s*(\w+_Type)\s*\*\s*\)\s*(\w+_BASE)\s*\)', text):
        instances.append((inst, tname, bases[base]))
    return types, instances


def parse_svd(path):
    root = ET.parse(path).getroot()
    raw = {p.findtext('name').strip(): p for p in root.iter('peripheral') if (p.findtext('name') or '').strip()}
    periphs = {}
    for name, p in raw.items():
        base = int(p.findtext('baseAddress').strip(), 0)
        src = raw[p.get('derivedFrom').strip()] if p.get('derivedFrom') else p
        regs = {}
        rs = src.find('registers')
        for r in (rs.iter('register') if rs is not None else []):
            fields = []
            fs = r.find('fields')
            for f in (fs.iter('field') if fs is not None else []):
                if f.findtext('bitOffset') is not None:
                    lsb, w = int(f.findtext('bitOffset'), 0), int(f.findtext('bitWidth'), 0)
                else:
                    msb, lsb = [int(x) for x in f.findtext('bitRange').strip('[]').split(':')]
                    w = msb - lsb + 1
                fields.append((f.findtext('name').strip(), lsb, w))
            regs[r.findtext('name').strip()] = (base + int(r.findtext('addressOffset').strip(), 0), fields)
        periphs[name] = (base, regs)
    return periphs


# Header instance -> (SVD peripheral, {header member: SVD register}) where the names differ
ALIASES = {
    'COMP1': ('COMP', {'CR': 'CR1'}),
    'COMP2': ('COMP', {'CR': 'CR2'}),
}


def svd_reg(regs, periph_name, member, renames=None):
    # Timer mode registers are split into _Output/_Input views in the SVD; use the output view
    for key in ((renames or {}).get(member), member, f'{member}_Output', f'{periph_name}_{member}'):
        if key in regs:
            return regs[key]
    return None


def main():
    types, instances = parse_header(sys.argv[1])
    periphs = parse_svd(sys.argv[2])
    by_base = {}
    for name, (base, regs) in periphs.items():
        by_base.setdefault(base, name)

    problems = []
    type_source = {}
    for inst, tname, base in instances:
        renames = None
        if inst in ALIASES:
            pname, renames = ALIASES[inst]
        else:
            pname = inst if inst in periphs else by_base.get(base)
        if pname is None:
            problems.append(f'{inst}: no SVD peripheral (base 0x{base:08X})')
            continue
        regs = periphs[pname][1]
        type_source.setdefault(tname, (inst, pname, renames))
        for member, off in types.get(tname, []):
            hit = svd_reg(regs, pname, member, renames)
            if hit is None:
                problems.append(f'{inst}->{member} @0x{base + off:08X}: not in SVD {pname}')
            elif hit[0] != base + off:
                problems.append(f'{inst}->{member}: header 0x{base + off:08X}, SVD {pname} 0x{hit[0]:08X}')

    out = ['/*', ' * FM33LC0XX register bit definitions', ' *',
           ' * Generated by tools/svd_header.py from the FMSH FM33LC0XX_DFP 3.0.4 SVD. Do not edit.',
           ' * Header/SVD address disagreements (settle with the datasheet before using these registers):']
    out += [f' *   {p}' for p in problems] or [' *   none']
    out += [' */', '', '#ifndef _FM33LC0XX_BITS_H_', '#define _FM33LC0XX_BITS_H_', '']
    emit = []
    for tname, (inst, pname, renames) in sorted(type_source.items()):
        if tname == 'COMP_Type':
            # Field names differ per comparator (CMP1O/CMP2O): one block per instance
            emit += [('COMP1', 'COMP1', 'COMP', ALIASES['COMP1'][1], tname), ('COMP2', 'COMP2', 'COMP', ALIASES['COMP2'][1], tname)]
        else:
            emit.append((tname[:-len('_Type')], inst, pname, renames, tname))
    for prefix, inst, pname, renames, tname in emit:
        regs = periphs[pname][1]
        out.append(f'// {tname} (SVD {pname}, instance {inst})')
        for member, _ in types[tname]:
            hit = svd_reg(regs, pname, member, renames)
            if hit is None:
                continue
            for fname, lsb, w in sorted(hit[1], key=lambda x: x[1]):
                mask = ((1 << w) - 1) << lsb
                out.append(f'#define {prefix}_{member}_{fname}_Pos {lsb}U')
                out.append(f'#define {prefix}_{member}_{fname}_Msk 0x{mask:08X}U')
        out.append('')
    out += ['#endif', '']
    open(sys.argv[3], 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
    print('\n'.join(problems) or 'no disagreements')


if __name__ == '__main__':
    main()
